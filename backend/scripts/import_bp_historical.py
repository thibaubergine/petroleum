def import_bp_data():
    """Import BP Statistical Review historical production data"""
    db = SessionLocal()
    
    try:
        print("🔄 Importing BP Statistical Review data...")
        print(f"📊 {len(BP_HISTORICAL_DATA)} countries")
        
        total_records = 0
        
        for country_code, country_data in BP_HISTORICAL_DATA.items():
            country_name = country_data['name']
            is_opec = country_data['opec']
            production_data = country_data['data']
            
            print(f"\n  📍 {country_name} ({country_code})")
            print(f"     OPEC: {is_opec}")
            print(f"     Years: {min(production_data.keys())}-{max(production_data.keys())}")
            print(f"     Records: {len(production_data)}")
            
            for year, value in production_data.items():
                # Check if exists
                existing = db.query(HistoricalProduction).filter(
                    HistoricalProduction.country_code == country_code,
                    HistoricalProduction.year == year,
                    HistoricalProduction.source_id == 'bp_statistical_2023'
                ).first()
                
                if existing:
                    # Update
                    existing.production_value = value
                    existing.country_name = country_name
                    existing.is_opec_member = is_opec
                else:
                    # Insert
                    record = HistoricalProduction(
                        country_code=country_code,
                        country_name=country_name,
                        year=year,
                        production_value=value,
                        source_id='bp_statistical_2023',
                        unit='mb/d',
                        is_opec_member=is_opec,
                        notes=f'BP Statistical Review 2023 - {country_name}'
                    )
                    db.add(record)
                
                total_records += 1
        
        db.commit()
        print(f"\n✅ Successfully imported {total_records} historical production records")
        print(f"📅 Coverage: 1965-2023 (59 years)")
        print(f"🌍 Countries: {len(BP_HISTORICAL_DATA)}")
        
        # Summary stats
        total_2023 = sum(data['data'].get(2023, 0) for data in BP_HISTORICAL_DATA.values())
        print(f"\n📈 2023 Total Production: {total_2023:.2f} mb/d")
        
        opec_count = sum(1 for data in BP_HISTORICAL_DATA.values() if data['opec'])
        print(f"🛢️  OPEC members: {opec_count}/{len(BP_HISTORICAL_DATA)}")
        
    except Exception as e:
        db.rollback()
        print(f"❌ Error: {str(e)}")
        raise
    finally:
        db.close()


if __name__ == "__main__":
    import_bp_data()
